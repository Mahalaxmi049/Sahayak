export function getServiceIdFromActions(allowedActions = []) {
  for (const act of allowedActions) {
    if (ACTION_SERVICES[act]) return ACTION_SERVICES[act];
  }
  return 'welfare_pensions';
}

export function getServiceLabel(serviceId, t) {
  if (!t) return 'Public Service';
  switch (serviceId) {
    case 'certificates_documents':
      return t.srvCertificatesDocuments || 'Certificates & Documents';
    case 'education_scholarships':
      return t.srvEducationScholarships || 'Education & Scholarships';
    case 'health_services':
      return t.srvHealthServices || 'Health Services';
    case 'citizen_services':
      return t.srvCitizenServices || 'Citizen Services';
    case 'welfare_pensions':
    default:
      return t.srvWelfarePensions || 'Welfare & Pensions';
  }
}

